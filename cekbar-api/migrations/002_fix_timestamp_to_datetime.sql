-- Fix: convert all TIMESTAMP columns to DATETIME for sqlx compatibility

-- orders: TIMESTAMP → DATETIME
ALTER TABLE orders
  MODIFY confirmed_at DATETIME NULL,
  MODIFY processed_at DATETIME NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  MODIFY completed_at DATETIME NULL;

-- services: TIMESTAMP → DATETIME
ALTER TABLE services
  MODIFY last_synced_at DATETIME NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

-- users: TIMESTAMP → DATETIME + enum update
ALTER TABLE users
  MODIFY role ENUM('user','reseller','admin','superadmin') NOT NULL DEFAULT 'user',
  MODIFY last_login_at DATETIME NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

-- payments: TIMESTAMP → DATETIME
ALTER TABLE payments
  MODIFY confirmed_at DATETIME NULL,
  MODIFY expires_at DATETIME NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

-- system_settings: TIMESTAMP → DATETIME
ALTER TABLE system_settings
  MODIFY updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

-- password_resets: TIMESTAMP → DATETIME
ALTER TABLE password_resets
  MODIFY expires_at DATETIME NOT NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- email_verifications: TIMESTAMP → DATETIME
ALTER TABLE email_verifications
  MODIFY expires_at DATETIME NOT NULL,
  MODIFY created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
